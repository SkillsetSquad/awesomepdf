import { act, render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { NextIntlClientProvider } from 'next-intl';
import { PDFDocument } from 'pdf-lib';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import en from '../../../../messages/en.json';
import ar from '../../../../messages/ar.json';
import { PDFToTIFFTool } from '@/components/tools/pdf-to-tiff/PDFToTIFFTool';
import { pdfToTiff } from '@/lib/pdf/processors/pdf-to-tiff';
import type { ProcessOutput } from '@/types/pdf';

let selectedFile: File;
const download = vi.fn();
vi.mock('@/lib/pdf/processors/pdf-to-tiff', () => ({ pdfToTiff: vi.fn() }));
vi.mock('@/components/tools/FileUploader', () => ({ FileUploader: ({ onFilesSelected }: { onFilesSelected: (files: File[]) => void }) => <button onClick={() => onFilesSelected([selectedFile])}>Choose TIFF source</button> }));
vi.mock('@/components/tools/DownloadButton', () => ({ DownloadButton: (props: { file: Blob; filename: string }) => { download(props); return <button>Download TIFF</button>; } }));

beforeEach(async () => {
  vi.clearAllMocks();
  vi.mocked(pdfToTiff).mockReset().mockResolvedValue({ success: true, result: new Blob(['tiff']) });
  const pdf = await PDFDocument.create();
  pdf.addPage([200, 300]); pdf.addPage([400, 500]);
  const bytes = await pdf.save();
  selectedFile = new File([new Uint8Array(bytes)], 'report.PDF', { type: 'application/pdf' });
  Object.defineProperty(selectedFile, 'arrayBuffer', { value: async () => new Uint8Array(bytes).buffer });
});

describe('TIFF output settings workspace', () => {
  it.each([['en', en], ['ar', ar]] as const)('preserves color, compression, DPI and the download contract through keyboard controls (%s)', async (locale, messages) => {
    let finish!: (output: ProcessOutput) => void;
    vi.mocked(pdfToTiff).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
    const intlError = vi.fn();
    const user = userEvent.setup();
    const t = messages.common.pdfToTiff;
    render(<NextIntlClientProvider locale={locale} messages={messages} onError={intlError}><PDFToTIFFTool /></NextIntlClientProvider>);
    await user.click(screen.getByRole('button', { name: 'Choose TIFF source' }));
    const color = await screen.findByRole('radiogroup', { name: t.colorModeLabel });
    const full = within(color).getByRole('radio', { name: t.colorModeFull });
    expect(full).toBeChecked();
    act(() => full.focus());
    await user.keyboard('{ArrowDown>}');
    await waitFor(() => expect(within(color).getByRole('radio', { name: t.colorModeGrayscale })).toBeChecked());
    await user.keyboard('{/ArrowDown}');
    await user.keyboard('{ArrowDown>}');
    await waitFor(() => expect(within(color).getByRole('radio', { name: t.colorModeMono })).toBeChecked());
    await user.keyboard('{/ArrowDown}');
    const compression = screen.getByRole('radiogroup', { name: t.compressionLabel });
    const packbits = within(compression).getByRole('radio', { name: t.compressionPackbits });
    expect(packbits).toBeChecked();
    act(() => packbits.focus());
    await user.keyboard('{ArrowUp>}');
    await waitFor(() => expect(within(compression).getByRole('radio', { name: t.compressionNone })).toBeChecked());
    await user.keyboard('{/ArrowUp}');
    const dpi = screen.getByRole('slider', { name: new RegExp(t.resolutionLabel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) });
    act(() => dpi.focus());
    await user.keyboard(locale === 'ar' ? '{ArrowLeft}' : '{ArrowRight}');
    expect(dpi).toHaveAttribute('aria-valuenow', '156');
    await user.keyboard('{Home}');
    expect(dpi).toHaveAttribute('aria-valuenow', '72');
    await user.keyboard('{End}');
    expect(dpi).toHaveAttribute('aria-valuenow', '600');
    const summary = screen.getByRole('region', { name: t.previewTitle });
    expect(summary).toHaveTextContent(t.colorModeMono);
    expect(summary).toHaveTextContent(t.compressionNone);
    expect(summary).toHaveTextContent('600 DPI');
    const process = screen.getByRole('button', { name: t.processButton });
    act(() => process.focus());
    await user.keyboard('{Enter}');
    expect(pdfToTiff).toHaveBeenCalledWith(selectedFile, { colorMode: 'mono', compression: 'none', dpi: 600, scale: 600 / 72 }, expect.any(Function));
    expect(full).toBeDisabled();
    expect(packbits).toBeDisabled();
    expect(dpi).toHaveAttribute('data-disabled');
    expect(process).toBeDisabled();
    const result = new Blob(['encoded TIFF']);
    await act(async () => finish({ success: true, result }));
    await screen.findByRole('button', { name: 'Download TIFF' });
    expect(download).toHaveBeenCalledWith(expect.objectContaining({ file: result, filename: 'report.tiff' }));
    expect(full).toBeEnabled();
    expect(intlError).not.toHaveBeenCalled();
    await user.click(screen.getByRole('button', { name: messages.common.buttons.remove }));
    expect(screen.queryByRole('button', { name: 'Download TIFF' })).toBeNull();
    expect(screen.getByRole('button', { name: 'Choose TIFF source' })).toBeEnabled();
  });

  it('preserves settings after a conversion error and permits retry', async () => {
    vi.mocked(pdfToTiff).mockRejectedValueOnce(new Error('Conversion failed'));
    const user = userEvent.setup();
    render(<NextIntlClientProvider locale="en" messages={en}><PDFToTIFFTool /></NextIntlClientProvider>);
    await user.click(screen.getByRole('button', { name: 'Choose TIFF source' }));
    const process = await screen.findByRole('button', { name: en.common.pdfToTiff.processButton });
    await user.click(process);
    expect(await screen.findByRole('alert')).toHaveTextContent('Conversion failed');
    expect(screen.getByRole('radio', { name: en.common.pdfToTiff.compressionPackbits })).toBeChecked();
    expect(process).toBeEnabled();
    await user.click(process);
    await waitFor(() => expect(screen.getByRole('button', { name: 'Download TIFF' })).toBeEnabled());
    expect(screen.queryByRole('alert')).toBeNull();
  });
});
